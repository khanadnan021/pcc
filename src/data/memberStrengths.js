/**
 * Fallback generator for any member if specific details are not pre-mapped
 */
export function getMemberDetails(member) {
  if (!member) return null;
  const mapped = MEMBER_PROFILES[member.id];
  if (mapped) {
    return {
      ...mapped,
      name: member.name,
      role: member.role,
      department: member.department,
      year: member.year,
      bio: member.bio,
      image: member.image,
      imageCandidates: member.imageCandidates,
      socials: member.socials
    };
  }

  // Smart inferred fallback based on category/role
  const isTech = member.category === 'Technical';
  const isDesign = member.category === 'Design';
  const isDocs = member.category === 'Documentation';
  const isMedia = member.category === 'Media & Marketing';

  return {
    superpower: isTech
      ? 'Technical Problem Solver & Builder'
      : isDesign
      ? 'Visual Designer & Creative Mind'
      : isDocs
      ? 'Technical Communicator & Researcher'
      : isMedia
      ? 'Community Evangelist & Storyteller'
      : 'Dedicated Club Contributor',
    quote: 'Striving for excellence through collaboration, curiosity, and code.',
    strengths: [
      {
        title: 'Core Domain Excellence',
        desc: `Brings focused expertise to the ${member.category} vertical, driving high execution standards.`
      },
      {
        title: 'Collaborative Execution',
        desc: 'Works closely with cross-functional verticals to ensure club events and projects succeed.'
      },
      {
        title: 'Continuous Innovation',
        desc: 'Always eager to learn new tools, technologies, and methodologies to enhance club output.'
      }
    ],
    skills: isTech
      ? ['Web Development', 'Problem Solving', 'Git', 'Data Structures', 'Teamwork']
      : isDesign
      ? ['UI Design', 'Figma', 'Visual Hierarchy', 'Branding', 'Creativity']
      : isDocs
      ? ['Technical Writing', 'Documentation', 'Research', 'Reporting', 'Organization']
      : ['Outreach', 'Communications', 'Content Creation', 'Event Support', 'Social Media'],
    highlights: [
      'Active contributor to Programmers Club initiatives',
      'Supported major college coding contests and student workshops'
    ],
    name: member.name,
    role: member.role,
    department: member.department,
    year: member.year,
    bio: member.bio,
    image: member.image,
    imageCandidates: member.imageCandidates,
    socials: member.socials
  };
}
